def apply_field_notes(meet):
    """Descriptions only; never round-trip lossy lookup/select metadata from the CLI."""
    for table, notes in FIELD_NOTES.items():
        for field in meet.remote.fields(meet.tables[table]):
            description = notes.get(field['field_name'])
            if table == 'preparation' and field['field_name'].startswith('第') and field['field_name'].endswith('轮组别'):
                description = '【自动引用】显示关联用户这一轮的实际组别，不是待分配候选。分组脚本更新成员关联后自动显示；请勿改写公式。'
            existing = field.get('description')
            if isinstance(existing, dict):
                existing = existing.get('text')
            if not description or existing == description:
                continue
            meet.remote.update_field(meet.tables[table], field, description=description)
            time.sleep(0.3)
